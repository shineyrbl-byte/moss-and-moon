type Key = keyof typeof en;

/** English is always here; the other languages are added by loadLang when someone picks them */
export const DICT: { en: Record<Key, string> } & Partial<Record<Lang, Record<Key, string>>> = { en };
/** Fetch a language's labels (once). English needs nothing. */
export async function loadLang(l: Lang) {
  if (DICT[l]) return;
  const m = l === "hi" ? await import("./i18n/hi.ts") : l === "mr" ? await import("./i18n/mr.ts") : await import("./i18n/kok.ts");
  DICT[l] = m.default;
}
/** One label, in the language if it's loaded, else English */
export const label = (l: Lang, k: Key) => DICT[l]?.[k] ?? DICT.en[k];
export type TKey = Key;

/** Fill {blanks} in a translated string */
export function fill(s: string, vars: Record<string, string | number>) {
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}
